// bake-instagram.js — resolve each venue's REAL Instagram profile and bake it into
// lib/baked-instagram.js, so the app links straight to the account instead of an
// Instagram search wall. Also re-validates existing baked handles and drops/replaces
// wrong ones (e.g. a bare "flash" that isn't the DC club).
//
//   node scripts/bake-instagram.js              # resolve up to --limit missing/invalid
//   node scripts/bake-instagram.js --limit 400
//   node scripts/bake-instagram.js --recheck    # also re-validate ALL existing handles
import { readFileSync, writeFileSync } from 'fs';
import { fileURLToPath } from 'url';
import path from 'path';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.join(__dirname, '..');
const LIB = path.join(ROOT, 'lib');
const arg = (f, d) => { const i = process.argv.indexOf(f); return i >= 0 ? (process.argv[i + 1] ?? true) : d; };
const LIMIT = Math.min(3000, parseInt(arg('--limit', '900'), 10) || 900);
const RECHECK = process.argv.includes('--recheck');
// gentle: the search proxy rate-limits, so keep concurrency low + a small delay
// between lookups. Resumable — already-baked handles are skipped on the next run.
const CONC = Math.max(1, parseInt(arg('--conc', '2'), 10) || 2);
const DELAY = Math.max(0, parseInt(arg('--delay', '450'), 10) || 450);
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

const { db } = await import('../lib/store.js');
const seedMod = await import('../lib/seed.js');
seedMod.seed();
const { resolveInstagramFor, igUrlValidForVenue } = await import('../lib/places.js');
const { BAKED_INSTAGRAM } = await import('../lib/baked-instagram.js');

const baked = { ...BAKED_INSTAGRAM };
const isSearch = (u) => /explore\/search/.test(String(u || ''));
const byId = Object.fromEntries(db.venues.map((v) => [v.id, v]));

// 1) drop only search-page fallbacks (never a real handle). A "suspect" existing
// handle (fails name-match, e.g. a bare "flash") is RE-resolved but only replaced
// if we find a better one — so we never lose a correct-but-generic handle.
for (const id of Object.keys(baked)) { const v = byId[id]; if (!v || isSearch(baked[id])) delete baked[id]; }
const missing = db.venues.filter((v) => !baked[v.id]);
const suspect = RECHECK ? db.venues.filter((v) => baked[v.id] && !igUrlValidForVenue(v.name, v.city, baked[v.id])) : [];
const targets = [...missing, ...suspect].slice(0, LIMIT);
console.log(`Venues: ${db.venues.length} | baked: ${Object.keys(baked).length} | missing: ${missing.length} | suspect: ${suspect.length} | this run: ${targets.length}`);

function writeBaked() {
  writeFileSync(path.join(LIB, 'baked-instagram.js'),
    '// AUTO-GENERATED by scripts/bake-instagram.js — real Instagram profile URLs per\n// venue id, resolved once and baked so the app links straight to the account.\n'
    + 'export const BAKED_INSTAGRAM = ' + JSON.stringify(baked) + ';\n');
}
let found = 0, replaced = 0, i = 0, sinceSave = 0;
async function worker() {
  while (i < targets.length) {
    const v = targets[i++]; const n = i; const had = baked[v.id];
    try {
      const url = await resolveInstagramFor(v);
      if (url && url !== had) {
        baked[v.id] = url; if (had) replaced++; else found++;
        console.log(`  [${n}/${targets.length}] ${had ? '↻' : '✓'} ${v.name} (${v.city}) -> ${url.replace('https://www.instagram.com/', '@').replace(/\/$/, '')}`);
        if (++sinceSave >= 30) { sinceSave = 0; writeBaked(); } // persist progress (resumable)
      } else if (n % 25 === 0) console.log(`  [${n}/${targets.length}] · …`);
      // url null → keep `had` as-is (never drop an existing handle without a replacement)
    } catch (e) { /* skip */ }
    if (DELAY) await sleep(DELAY);
  }
}
await Promise.all(Array.from({ length: CONC }, worker));

console.log(`\nResolved ${found} new + ${replaced} replaced Instagram handles (of ${targets.length} tried). Writing baked-instagram.js…`);
writeBaked();
console.log(`Done. Total baked: ${Object.keys(baked).length}.`);
